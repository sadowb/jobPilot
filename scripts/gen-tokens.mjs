// Generates src/renderer/src/styles/tokens.css from design/tokens.json (V17, resolved from jp8.css).
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../design/tokens.json', import.meta.url), 'utf8'));
const stacks = {
  '--sans': "'Geist Variable','Geist',-apple-system,system-ui,sans-serif",
  '--serif': "'Newsreader Variable','Newsreader',ui-serif,Georgia,serif",
  '--mono': "'Geist Mono Variable','Geist Mono',ui-monospace,Menlo,monospace",
  '--logo': "'Bagel Fat One',var(--sans)",
};
const block = (selector, vars) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n')}\n}\n`;

const out = [
  '/* GENERATED by scripts/gen-tokens.mjs from design/tokens.json. Do not edit. */\n',
  block(':root', { ...stacks, ...tokens.light }),
  block('.dark', tokens.dark),
  block(
    ':root',
    Object.fromEntries(
      Object.entries(tokens.avatar.light).flatMap(([n, c]) => [
        [`--${n}-bg`, c.bg],
        [`--${n}-fg`, c.fg],
      ]),
    ),
  ),
  block(
    '.dark',
    Object.fromEntries(
      Object.entries(tokens.avatar.dark).flatMap(([n, c]) => [
        [`--${n}-bg`, c.bg],
        [`--${n}-fg`, c.fg],
      ]),
    ),
  ),
  block(
    ':root',
    Object.fromEntries(Object.entries(tokens.cap).map(([k, v]) => [`--cap-${k.replaceAll('_', '-')}`, v])),
  ),
].join('\n');
writeFileSync(new URL('../src/renderer/src/styles/tokens.css', import.meta.url), out);
console.log('wrote tokens.css');
